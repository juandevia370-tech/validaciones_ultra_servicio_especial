-- Migración 002 (PostgreSQL). Ejecutar en el SQL Editor de la base de producción.
-- Tabla de usuarios para la autenticación propia del sistema (sin Supabase Auth).
-- Las contraseñas se guardan solo como hash bcrypt (password_hash de PHP).
-- Corre en una transacción y se puede repetir.

BEGIN;

CREATE TABLE IF NOT EXISTS transporte.usuarios (
    id                integer      GENERATED BY DEFAULT AS IDENTITY,
    nombre            varchar(100) NOT NULL,
    correo            varchar(254) NOT NULL,
    contrasena_hash   varchar(255) NOT NULL,
    activo            boolean      NOT NULL DEFAULT true,
    intentos_fallidos integer      NOT NULL DEFAULT 0,
    bloqueado_hasta   timestamptz  NULL,
    ultimo_acceso     timestamptz  NULL,
    creado_en         timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT usuarios_pkey PRIMARY KEY (id),
    CONSTRAINT usuarios_correo_key UNIQUE (correo)
);

-- Nadie fuera del servidor PHP puede leer esta tabla.
ALTER TABLE transporte.usuarios ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON transporte.usuarios FROM anon';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        EXECUTE 'REVOKE ALL ON transporte.usuarios FROM authenticated';
    END IF;
END $$;
REVOKE ALL ON transporte.usuarios FROM PUBLIC;

-- Traslado de los usuarios que existían en Supabase Auth, CONSERVANDO SUS
-- CONTRASEÑAS: Supabase también las guarda con bcrypt, que PHP verifica sin
-- problema. Solo se ejecuta si la base tiene el esquema "auth" de Supabase.
DO $$
BEGIN
    IF to_regclass('auth.users') IS NOT NULL THEN
        INSERT INTO transporte.usuarios (nombre, correo, contrasena_hash, activo)
        SELECT
            COALESCE(NULLIF(u.raw_user_meta_data ->> 'name', ''), split_part(u.email, '@', 1)),
            lower(u.email),
            u.encrypted_password,
            true
        FROM auth.users u
        WHERE u.email IS NOT NULL
          AND u.encrypted_password LIKE '$2%'
          AND u.deleted_at IS NULL
        ON CONFLICT (correo) DO NOTHING;
    END IF;
END $$;

COMMIT;

-- Verificación (no muestra contraseñas)
SELECT id, nombre, correo, activo FROM transporte.usuarios ORDER BY id;
