-- Esquema PostgreSQL (Supabase) del sistema de transporte.
-- Equivalente al esquema MySQL/MariaDB de XAMPP (sistema_transporte):
-- mismos nombres de tablas, columnas, longitudes, claves primarias,
-- restricciones UNIQUE y claves foráneas (ON DELETE/UPDATE RESTRICT,
-- el comportamiento por defecto de InnoDB).
--
-- Las tablas se crean en el esquema privado "transporte", que la API REST
-- pública de Supabase no expone. Además se activa RLS sin políticas y se
-- retiran permisos a los roles anon/authenticated, de modo que solo el
-- servidor PHP (rol postgres) puede leer y escribir.

CREATE SCHEMA IF NOT EXISTS transporte;

CREATE TABLE transporte.clientes (
    id        integer GENERATED BY DEFAULT AS IDENTITY,
    nombre    varchar(100) NOT NULL,
    documento varchar(20)  NOT NULL,
    correo    varchar(100) NOT NULL,
    telefono  varchar(20)  NOT NULL,
    CONSTRAINT clientes_pkey PRIMARY KEY (id),
    CONSTRAINT clientes_documento_key UNIQUE (documento)
);

CREATE TABLE transporte.conductores (
    id        integer GENERATED BY DEFAULT AS IDENTITY,
    nombre    varchar(100) NOT NULL,
    documento varchar(20)  NOT NULL,
    licencia  varchar(30)  NOT NULL,
    telefono  varchar(20)  NOT NULL,
    observaciones text     NULL,
    CONSTRAINT conductores_pkey PRIMARY KEY (id),
    CONSTRAINT conductores_documento_key UNIQUE (documento),
    CONSTRAINT conductores_licencia_key UNIQUE (licencia)
);

CREATE TABLE transporte.destinos (
    id                integer GENERATED BY DEFAULT AS IDENTITY,
    ciudad_origen     varchar(100)   NOT NULL,
    direccion_origen  varchar(150)   NULL,
    ciudad_destino    varchar(100)   NOT NULL,
    direccion_destino varchar(150)   NULL,
    tarifa            numeric(12, 2) NOT NULL,
    CONSTRAINT destinos_pkey PRIMARY KEY (id)
);

CREATE TABLE transporte.pasajeros (
    id         integer GENERATED BY DEFAULT AS IDENTITY,
    nombre     varchar(100) NOT NULL,
    documento  varchar(20)  NOT NULL,
    telefono   varchar(20)  NULL,
    cliente_id integer      NOT NULL,
    CONSTRAINT pasajeros_pkey PRIMARY KEY (id),
    CONSTRAINT pasajeros_documento_key UNIQUE (documento),
    CONSTRAINT fk_pasajero_cliente FOREIGN KEY (cliente_id)
        REFERENCES transporte.clientes (id) ON UPDATE RESTRICT ON DELETE RESTRICT
);
CREATE INDEX idx_pasajeros_cliente_id ON transporte.pasajeros (cliente_id);

CREATE TABLE transporte.vehiculos (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    placa        varchar(10) NOT NULL,
    tipo         varchar(30) NOT NULL,
    marca        varchar(50) NOT NULL,
    modelo       varchar(50) NOT NULL,
    capacidad    integer     NOT NULL,
    conductor_id integer     NOT NULL,
    CONSTRAINT vehiculos_pkey PRIMARY KEY (id),
    CONSTRAINT vehiculos_placa_key UNIQUE (placa),
    CONSTRAINT fk_vehiculo_conductor FOREIGN KEY (conductor_id)
        REFERENCES transporte.conductores (id) ON UPDATE RESTRICT ON DELETE RESTRICT
);
CREATE INDEX idx_vehiculos_conductor_id ON transporte.vehiculos (conductor_id);

CREATE TABLE transporte.servicios (
    id             integer GENERATED BY DEFAULT AS IDENTITY,
    cliente_id     integer     NOT NULL,
    pasajero_id    integer     NOT NULL,
    conductor_id   integer     NOT NULL,
    vehiculo_id    integer     NOT NULL,
    destino_id     integer     NOT NULL,
    telefono_contacto varchar(20)  NULL,
    ciudad_origen     varchar(100) NULL,
    direccion_origen  varchar(150) NULL,
    ciudad_destino    varchar(100) NULL,
    direccion_destino varchar(150) NULL,
    fecha_servicio date        NOT NULL,
    hora_servicio  time        NOT NULL,
    hora_llegada   time        NULL,
    ticket         varchar(30) NULL,
    flete          numeric(12, 2) NULL,
    estado         varchar(30) NOT NULL,
    observaciones  text        NULL,
    CONSTRAINT servicios_pkey PRIMARY KEY (id),
    CONSTRAINT fk_servicio_cliente FOREIGN KEY (cliente_id)
        REFERENCES transporte.clientes (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_servicio_pasajero FOREIGN KEY (pasajero_id)
        REFERENCES transporte.pasajeros (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_servicio_conductor FOREIGN KEY (conductor_id)
        REFERENCES transporte.conductores (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_servicio_vehiculo FOREIGN KEY (vehiculo_id)
        REFERENCES transporte.vehiculos (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_servicio_destino FOREIGN KEY (destino_id)
        REFERENCES transporte.destinos (id) ON UPDATE RESTRICT ON DELETE RESTRICT
);
CREATE INDEX idx_servicios_cliente_id   ON transporte.servicios (cliente_id);
CREATE INDEX idx_servicios_pasajero_id  ON transporte.servicios (pasajero_id);
CREATE INDEX idx_servicios_conductor_id ON transporte.servicios (conductor_id);
CREATE INDEX idx_servicios_vehiculo_id  ON transporte.servicios (vehiculo_id);
CREATE INDEX idx_servicios_destino_id   ON transporte.servicios (destino_id);

-- Sesiones PHP (necesarias en Vercel/serverless, SESSION_DRIVER=database).
CREATE TABLE transporte.sesiones (
    id     varchar(128) NOT NULL,
    datos  text         NOT NULL,
    expira timestamptz  NOT NULL,
    CONSTRAINT sesiones_pkey PRIMARY KEY (id)
);
CREATE INDEX idx_sesiones_expira ON transporte.sesiones (expira);

-- Seguridad: nada de acceso desde la API pública (clave publishable / anon).
ALTER TABLE transporte.sesiones    ENABLE ROW LEVEL SECURITY;
ALTER TABLE transporte.clientes    ENABLE ROW LEVEL SECURITY;
ALTER TABLE transporte.conductores ENABLE ROW LEVEL SECURITY;
ALTER TABLE transporte.destinos    ENABLE ROW LEVEL SECURITY;
ALTER TABLE transporte.pasajeros   ENABLE ROW LEVEL SECURITY;
ALTER TABLE transporte.vehiculos   ENABLE ROW LEVEL SECURITY;
ALTER TABLE transporte.servicios   ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON SCHEMA transporte FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA transporte FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA transporte FROM PUBLIC, anon, authenticated;
